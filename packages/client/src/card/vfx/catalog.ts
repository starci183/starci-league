/** Kiểm tra cả roster thực tế và mọi tham chiếu cast/travel/impact. */
export function validateVfx(): string[] {
    const errors: string[] = []
    const check = (label: string, style: SkillVfx) => {
        for (const name of [style.cast,
            style.travel,
            style.impact,
            style.extra]) if (name && !getVfx(name)) errors.push(`${label}: thiếu ${name}`)
    }
    for (const hero of cg.implementedHeroes()) {
        if (!hasHeroVfx(hero.id)) errors.push(`Chưa map tướng ${hero.id}`)
        const basic = heroBasicVfxSequence(hero.id,
            hero.damage,
            hero.role)
        if (!basic.length) errors.push(`${hero.id}/basic: danh sách VFX rỗng`)
        basic.forEach((style, i) => check(`${hero.id}/basic/${i}`,
            style))
    }
    for (const [id,
        skills] of heroVfxEntries()) for (const [key,
        style] of Object.entries(skills)) check(`${id}/${key}`,
        style)
    for (const [id,
        style] of spellVfxEntries()) check(`spell/${id}`,
        style)
    for (const id of vfxNames()) if (!metadata.has(id)) errors.push(`Thiếu mô tả VFX ${id}`)
    return errors
}
