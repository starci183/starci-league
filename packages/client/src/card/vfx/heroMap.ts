/** Hiệu ứng đòn đánh thường theo vai trò + loại sát thương */
export function basicVfx(role: string, damage: "physical" | "magic"): SkillVfx {
    const magic = damage === "magic"
    switch (role) {
    case "marksman":
        return magic
            ? fx("arrow",
                "magicHit",
                0x8ad0ff,
                0xffffff)
            : fx("arrow",
                "physicalHit",
                0xe8e0c0,
                0xffffff)
    case "mage":
        return fx("bolt",
            "magicHit",
            0xb08aff,
            0xe8d8ff)
    case "support":
        return fx("bolt",
            "magicHit",
            0x90e0ff,
            0xffffff)
    case "assassin":
        return magic
            ? fx("slash",
                "magicHit",
                0xe03050,
                0xffffff)
            : fx("slash",
                "slashHit",
                0xd8d8e8,
                0xffffff)
    case "tank":
        return magic
            ? fx("slash",
                "magicHit",
                0xffd060,
                0xffffff)
            : fx("slash",
                "physicalHit",
                0xb0a090,
                0xffffff)
    case "fighter":
        return magic
            ? fx("slash",
                "magicHit",
                0xffa060,
                0xffffff)
            : fx("slash",
                "slashHit",
                0xe0d0c0,
                0xffffff)
    default:
        return magic
            ? fx("bolt",
                "magicHit",
                0xb08aff,
                0xffffff)
            : fx("slash",
                "physicalHit",
                0xe0d0c0,
                0xffffff)
    }
}
