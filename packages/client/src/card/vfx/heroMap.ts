/** Đường dẫn icon chiêu để dispatcher truyền vào ctx.icon */
export const skillIcon = (hero: string, key: SkillKey): string => `/card_skills/${hero}_${key}.png`

export const DEFAULT_VFX: SkillVfx = {
    travel: "bolt",
    impact: "burst",
    color: 0xffffff,
    color2: 0x9ad0ff
}

const fx = (
    travel: string,
    impact: string,
    color: number,
    color2: number,
    cast?: string,
    intensity?: number
): SkillVfx => ({
    travel,
    impact,
    color,
    color2,
    cast,
    intensity
})

/** Chiêu cuối: cường độ 2 */
const ult = (
    travel: string,
    impact: string,
    color: number,
    color2: number,
    cast?: string
): SkillVfx => fx(travel,
    impact,
    color,
    color2,
    cast,
    2)

/** Nội tại: hiệu ứng tại chỗ nhẹ */
const passive = (
    impact: string,
    color: number,
    color2: number
): SkillVfx => fx("none",
    impact,
    color,
    color2)

